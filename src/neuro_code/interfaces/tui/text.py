if _ENGLISH.keys() != _CHINESE.keys():
    raise RuntimeError("TUI translation catalogs must contain identical keys")

_CATALOGS: Final[Mapping[UiLanguage, Mapping[str, str]]] = {
    UiLanguage.ENGLISH: _ENGLISH,
    UiLanguage.SIMPLIFIED_CHINESE: _CHINESE,
}


def ui_text(locale: UiLanguage, key: str, **values: object) -> str:
    """Render one owned UI string while leaving conversation content untouched.

    渲染一个由本模块管理的 UI 字符串,同时保持会话内容不变."""

    template = _CATALOGS[locale][key]
    return template.format_map(values)


_KNOWN_ERROR_TEXT_KEYS: Final[Mapping[str, str]] = {
    "explicit compaction requires a persisted session": (
        "error.compaction_requires_persisted_session"
    ),
}


def localize_error_text(locale: UiLanguage, text: str) -> str:
    """Replace known application error messages with localized equivalents.

    Application and domain layers raise language-neutral English messages. The
    TUI keeps a bounded map of the user-facing ones so transcript errors read
    in the selected interface language; unknown messages stay verbatim.

    应用层与领域层抛出语言中立的英文消息.TUI 维护一份有界的用户可见映射,
    使会话中的错误与界面语言一致;未收录的消息保持原样.
    """

    localized = text
    for raw, key in _KNOWN_ERROR_TEXT_KEYS.items():
        if raw in localized:
            localized = localized.replace(raw, ui_text(locale, key))
    return localized


def language_name(language: UiLanguage, *, in_language: UiLanguage) -> str:
    names = {
        UiLanguage.ENGLISH: {
            UiLanguage.ENGLISH: "English",
            UiLanguage.SIMPLIFIED_CHINESE: "Simplified Chinese",
        },
        UiLanguage.SIMPLIFIED_CHINESE: {
            UiLanguage.ENGLISH: "英语",
            UiLanguage.SIMPLIFIED_CHINESE: "简体中文",
        },
    }
    return names[in_language][language]


